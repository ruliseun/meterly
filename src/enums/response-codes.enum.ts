export enum ResponseCodeEnum {
  // Success Responses (2xx)
  OK = 200,
  CREATED = 201,
  ACCEPTED = 202,
  NO_CONTENT = 204,

  // Client Errors (4xx)
  BAD_REQUEST = 400,
  UNAUTHORIZED = 401,
  FORBIDDEN = 403,
  NOT_FOUND = 404,
  METHOD_NOT_ALLOWED = 405,
  CONFLICT = 409,
  UNPROCESSABLE_ENTITY = 422,

  // Server Errors (5xx)
  INTERNAL_SERVER_ERROR = 500,
  NOT_IMPLEMENTED = 501,
  BAD_GATEWAY = 502,
  SERVICE_UNAVAILABLE = 503,
  GATEWAY_TIMEOUT = 504,

  // Application-specific Responses (1xxx+)
  USER_ALREADY_EXISTS = 1001,
  USER_NOT_FOUND = 1002,
  INVALID_CREDENTIALS = 1003,
  ACCESS_DENIED = 1004,
  SESSION_EXPIRED = 1005,
  TOKEN_INVALID = 1006,
  VALIDATION_FAILED = 1007,
  RESOURCE_LOCKED = 1008,
  RATE_LIMIT_EXCEEDED = 1009,
  EMAIL_NOT_VERIFIED = 1010,
}
